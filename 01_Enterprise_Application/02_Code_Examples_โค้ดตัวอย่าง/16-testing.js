// Software Testing: เขียน Test Case ให้ฟังก์ชันแล้วรันตรวจอัตโนมัติ
// สไลด์ 91–97 · รันด้วย: node 16-testing.js

// ---------------------------------------------------------------- ฟังก์ชันที่จะทดสอบ
// Requirement: แจ้งเตือนเมื่อแรงดัน "เกิน 240 V" และค่าว่างหรือไม่ใช่ตัวเลขต้องแจ้งว่าข้อมูลไม่ถูกต้อง
function checkVoltage(input) {
  if (input === '' || input === null || input === undefined) return 'ข้อมูลไม่ถูกต้อง';
  const v = Number(input);
  if (Number.isNaN(v)) return 'ข้อมูลไม่ถูกต้อง';
  return v > 240 ? 'เตือน' : 'ปกติ';
}

// ---------------------------------------------------------------- Test Case
// แต่ละแถวคือ 1 กรณี: รหัส, คำอธิบาย, ข้อมูลทดสอบ, ผลที่คาดหวัง
const testCases = [
  ['TC-01', 'กรณีปกติ', '230', 'ปกติ'],
  ['TC-02', 'ค่าขอบ: เท่ากับ 240 ต้องยังไม่เตือน', '240', 'ปกติ'],
  ['TC-03', 'ค่าขอบ: เกิน 240 เล็กน้อย', '240.1', 'เตือน'],
  ['TC-04', 'กรณีผิดปกติ: ค่าสูงมาก', '500', 'เตือน'],
  ['TC-05', 'ข้อมูลผิดรูปแบบ: ตัวอักษร', 'abc', 'ข้อมูลไม่ถูกต้อง'],
  ['TC-06', 'ข้อมูลผิดรูปแบบ: ช่องว่าง', '', 'ข้อมูลไม่ถูกต้อง']
];

// ---------------------------------------------------------------- รันทุกกรณีแล้วสรุปผล
let passed = 0;
testCases.forEach(([id, description, input, expected]) => {
  const actual = checkVoltage(input);
  const ok = actual === expected;
  if (ok) passed++;
  console.log(`${ok ? 'PASS' : 'FAIL'} ${id} ${description} | ได้ "${actual}" คาดหวัง "${expected}"`);
});
console.log(`ผ่าน ${passed}/${testCases.length} กรณี`);   // → ผ่าน 6/6 กรณี

// ---------------------------------------------------------------- ลองทำให้ test จับ bug ได้
